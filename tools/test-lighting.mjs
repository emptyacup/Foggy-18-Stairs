import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createSky } from '../src/core/sky.js';
import { Halos } from '../src/core/halos.js';

const scene = new THREE.Scene();
const shared = { uTime: { value: 0 }, uDaylight: { value: 0 } };
const sky = createSky(scene, shared);
const halos = new Halos();
halos.add({ position: [0, 1, 0], color: 0xffffff, size: 1, intensity: 1 });
const haloMesh = halos.build();
scene.add(haloMesh);
haloMesh.material.uniforms.fogDensity.value = scene.fog.density;
assert.equal(typeof sky.setDaylight, 'function', '天空必须支持原位日夜切换');
const fog = scene.fog.color;
const night = { color: fog.clone(), density: scene.fog.density, light: sky.hemi.intensity };
sky.setDaylight(true);
assert.equal(shared.uDaylight.value, 1);
assert.equal(scene.fog.color, fog, '保留已被 shader 引用的雾色对象');
assert.ok(fog.r + fog.g + fog.b > night.color.r + night.color.g + night.color.b);
assert.ok(sky.hemi.intensity > night.light);
assert.ok(scene.fog.density < night.density);
assert.equal(haloMesh.material.uniforms.fogDensity.value, scene.fog.density, '光晕同步日景雾密度');
sky.setDaylight(false);
assert.equal(shared.uDaylight.value, 0);
assert.ok(fog.equals(night.color));
assert.equal(scene.fog.density, night.density);
assert.equal(sky.hemi.intensity, night.light);
assert.equal(haloMesh.material.uniforms.fogDensity.value, scene.fog.density);
console.log('Lighting toggle OK');
